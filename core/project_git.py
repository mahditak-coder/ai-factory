"""AF-25 — autonomous, PROJECT-SCOPED Git & GitHub management.

Every operation is scoped to exactly one project directory:
``projects/<name>``. The AI Factory root is never treated as a product repo,
and a parent repository never leaks another project's changes into a push.

Design rules:
  * local repo creation and GitHub repo creation happen ONLY after an explicit,
    one-shot confirmation (core.confirmations); read-only inspection never
    asks for confirmation and never mutates anything;
  * GitHub auth uses the user's existing `gh` credential store exclusively —
    no password, no token in code/config/reports (local helper is
    `!gh auth git-credential`, which never touches a token file);
  * private is the default for every newly created repository;
  * no force push, no history rewrite, no deletion of existing content;
  * the per-project settings file lives in `.factory/` (already excluded from
    exports, releases and commits).
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import time
from pathlib import Path

import core.config as config
from core import git_sync, paths

log = __import__("logging").getLogger("ai-factory.project-git")

OK, FAIL, SKIP, NEEDS_CONFIRM = "ok", "failed", "not_done", "needs_confirmation"
_LABELS = {OK: "موفق", FAIL: "ناموفق", SKIP: "انجامنشده", NEEDS_CONFIRM: "نیاز به تأیید"}


def settings_path(project: str) -> Path:
    d = paths.project_dir(project)
    return d / ".factory" / "git-github.json"


def load_settings(project: str) -> dict:
    try:
        d = json.loads(settings_path(project).read_text(encoding="utf-8"))
        return d if isinstance(d, dict) else {}
    except (OSError, ValueError):
        return {}


def save_settings(project: str, data: dict) -> dict:
    p = settings_path(project)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    try:
        os.chmod(tmp, 0o600)
    except OSError:
        pass
    tmp.replace(p)
    return dict(data)


def active_project(session_id: str = "") -> tuple[str | None, str]:
    """Resolve the ACTIVE project from an OpenCode session directory.

    Returns (project_name, note). A session located at the AI Factory root —
    or anywhere outside projects/ — is refused explicitly: that is exactly the
    scope confusion this feature must prevent.
    """
    if not session_id:
        return None, "نشست فعال مشخص نشد"
    try:
        from core.model_gateway import gateway
        loc = gateway().session_location(session_id)
    except Exception as exc:  # noqa: BLE001 — bridge may be down
        return None, "مکان نشست خوانده نشد: %s" % str(exc)[:120]
    if not loc:
        return None, "نشست یافت نشد"
    try:
        real = Path(loc).resolve()
        base = config.PROJECTS_DIR.resolve()
    except OSError:
        return None, "مسیر نشست نامعتبر"
    if real == config.PROJECT_ROOT.resolve():
        return None, "نشست روی ریشهٔ AI Factory است — ریشه هرگز بهعنوان پروژه شناخته نمیشود"
    if real == base or base not in real.parents:
        return None, "نشست خارج از پوشهٔ projects است"
    name = real.name
    if not re.match(config.PROJECT_NAME_RE, name) or not real.is_dir():
        return None, "نام پروژهٔ نشست نامعتبر است"
    return name, "پروژهٔ فعال از نشست: %s" % name


def _git(root: Path, *args: str, timeout: float = 40.0) -> tuple[int, str, str]:
    return git_sync._git(root, *args, timeout=timeout)


def suggest_name(project: str) -> str:
    """A GitHub-safe name proposed from the project (never from a folder guess)."""
    raw = project.strip().replace(" ", "-")
    if re.match(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,99}$", raw):
        return raw
    digest = hashlib.sha1(project.encode("utf-8")).hexdigest()[:6]
    return "af-project-" + digest


def gitignore_for(project: str) -> str:
    """Type-tailored .gitignore; never overwrites an existing one."""
    from core import factory, smart_release as sr
    d = paths.project_dir(project)
    kind = sr.detect_type(d)["kind"]
    common = [
        "# AI Factory — generated by Smart Release (AF-25)",
        ".factory/",
        ".env", "*.token", "*.pem", "*.key", "*.jks", "*.keystore", "*.p12",
        "*.db", "*.sqlite", "*.sqlite3", "*.log", "*.pid", "*.out", "*.tmp",
        "__pycache__/", "*.pyc", "node_modules/",
    ]
    if kind == "android":
        extra = ["build/", "*.apk", "*.aab", "*.apks", "*.idsig", "*.dex", "*.class",
                 ".backups/", "local.properties"]
    elif kind == "node":
        extra = ["dist/", "out/", "coverage/"]
    elif kind == "python":
        extra = ["data/", "dist/", "build/", ".pytest_cache/", "venv/"]
    else:
        extra = ["dist/", "build/"]
    return "\n".join(common + ["", "# type: " + kind] + extra) + "\n"


def repo_state(project: str) -> dict:
    """Read-only, strictly project-scoped repository + GitHub picture."""
    d = paths.project_dir(project)
    own = (d / ".git").exists()
    branch, head, commits = "", "", 0
    changed, conflicts, ahead, behind = [], [], 0, 0
    remote_name, remote_info = "", {}
    if own:
        code, o, _ = _git(d, "rev-parse", "--abbrev-ref", "HEAD")
        branch = o.strip() if code == 0 else ""
        code, o, _ = _git(d, "rev-parse", "HEAD")
        head = o.strip() if code == 0 else ""
        _, o, _ = _git(d, "rev-list", "--count", "HEAD")
        commits = int(o.strip()) if o.strip().isdigit() else 0
        changed = git_sync._changed_files(d)
        _, o, _ = _git(d, "ls-files", "-u")
        conflicts = [x for x in o.splitlines() if x.strip()]
        _, o, _ = _git(d, "config", "--get", "branch.%s.remote" % branch) if branch else (0, "", "")
        remote_name = o.strip()
        if not remote_name:
            _, o, _ = _git(d, "remote", "get-url", "origin")
            if o.strip():
                remote_name, remote = "origin", o.strip()
            else:
                remote = ""
        else:
            _, remote, _ = _git(d, "remote", "get-url", remote_name)
            remote = remote.strip()
        remote_info = git_sync._safe_remote(remote)
        if remote_name and branch:
            _, o, _ = _git(d, "fetch", remote_name, branch, timeout=45)
            code, o, _ = _git(d, "rev-list", "--left-right", "--count",
                              "HEAD...@{upstream}", timeout=20)
            if code == 0 and o.strip():
                try:
                    ahead, behind = (int(x) for x in o.split()[:2])
                except (ValueError, IndexError):
                    pass
    else:
        parent = None
        for cand in [d, *d.parents]:
            if (cand / ".git").exists() and cand != d:
                parent = str(cand)
                break
            if cand == config.PROJECT_ROOT.resolve():
                break
        remote_info = {"raw_present": False}
        if parent:
            remote_info["note"] = ("پروژه داخل مخزن والد «%s» است — هرگز از آن سطح ارسال نمیشود"
                                   % parent)

    login = github_login()
    settings = load_settings(project)
    gh_repo = {}
    target = remote_info.get("repo") or settings.get("repo_name") or ""
    if target and login and shutil.which("gh"):
        gh_repo = github_repo_view(target)
    return {
        "project": project, "project_root": str(d), "own_repo": own,
        "parent_repo_note": remote_info.get("note", ""),
        "branch": branch, "head": head, "commits": commits,
        "changed_count": len(changed), "conflicts": conflicts,
        "remote": remote_name, "remote_info": remote_info,
        "ahead": ahead, "behind": behind,
        "github_login": login, "github_repo": gh_repo,
        "settings": settings,
        "connected": bool(own and remote_name),
        "status": OK,
    }


def github_login() -> str | None:
    """The signed-in GitHub login, via the user's gh credential store.

    Only the login name is returned; no token ever enters a report or file.
    """
    if not shutil.which("gh"):
        return None
    p = subprocess.run(["gh", "api", "user", "--jq", ".login"],
                       capture_output=True, text=True, timeout=25)
    if p.returncode != 0:
        return None
    login = p.stdout.strip()
    return login or None


def github_repo_view(full_or_name: str) -> dict:
    if not full_or_name or not shutil.which("gh"):
        return {"exists": False, "reason": "gh موجود نیست"}
    p = subprocess.run(["gh", "repo", "view", full_or_name, "--json",
                        "visibility,nameWithOwner,url"],
                       capture_output=True, text=True, timeout=25)
    if p.returncode != 0:
        return {"exists": False, "reason": "مخزن یافت نشد یا دسترسی نیست"}
    try:
        info = json.loads(p.stdout)
        return {"exists": True,
                "visibility": str(info.get("visibility") or "").upper(),
                "nameWithOwner": info.get("nameWithOwner") or full_or_name,
                "url": info.get("url") or ""}
    except (ValueError, TypeError):
        return {"exists": False, "reason": "پاسخ gh نامعتبر"}


def _safe_add_list(project: str) -> list[str]:
    """Files eligible for an INITIAL commit — secrets/build data never included."""
    d = paths.project_dir(project)
    out = []
    for f in sorted(d.rglob("*")):
        if not f.is_file():
            continue
        rel = f.relative_to(d).as_posix()
        c = git_sync._classify(rel, d, is_public=False)
        if c["allowed"]:
            out.append(rel)
    return out


def init_local_repo(project: str) -> dict:
    """Create a PRIVATE-to-device git repo for this project (no remote yet).

    Adds a tailored .gitignore if needed, stages only safe source files and
    makes one initial commit. Nothing is deleted or overwritten.
    """
    d = paths.project_dir(project)
    if (d / ".git").exists():
        return {"status": OK, "created": False, "note": "مخزن محلی از قبل وجود دارد"}
    gi = d / ".gitignore"
    created_gi = False
    if not gi.exists():
        gi.write_text(gitignore_for(project), encoding="utf-8")
        created_gi = True
    git_sync_time = time.strftime("%Y%m%d-%H%M%S")
    _git(d, "init", "-q", "-b", "main")
    _git(d, "config", "user.name", "AI Factory")
    _git(d, "config", "user.email", "ai-factory@localhost")
    # only safe project files — never `git add .`
    allowed = _safe_add_list(project)
    if allowed:
        code, _, err = _git(d, "add", "--", *allowed)
        if code != 0:
            return {"status": FAIL, "created": False,
                    "note": "افزودن فایلها ناموفق: " + git_sync._san(err, 200)}
    _git(d, "commit", "-qm", "Smart Release: initial project commit (%s)" % git_sync_time)
    return {"status": OK, "created": True, "gitignore_created": created_gi,
            "files_added": len(allowed), "root": str(d),
            "note": "مخزن اختصاصی پروژه ساخته شد (ریشهٔ AI Factory دستنخورده)"}


def connect_remote(project: str, repo_name: str, create: bool,
                   private: bool = True) -> dict:
    """Create (or attach) the GitHub repo, link it and push the initial commit.

    Credentials come from the user's `gh` store via a LOCAL credential helper;
    no token is written to a project file, git config or report.
    """
    d = paths.project_dir(project)
    login = github_login()
    if not login:
        return {"status": FAIL, "note": "وارد GitHub نشدهاید — ابتدا `gh auth login` "
                                       "را تکمیل و سپس تأیید کنید", "created": False}
    full = repo_name if "/" in repo_name else ("%s/%s" % (login, repo_name))
    steps: list[dict] = []
    if create:
        view = github_repo_view(full)
        if not view.get("exists"):
            flag = "--private" if private else "--public"
            p = subprocess.run(["gh", "repo", "create", full, flag,
                                "--description", "AI Factory Smart Release — " + project],
                               capture_output=True, text=True, timeout=60)
            if p.returncode != 0:
                return {"status": FAIL, "created": False,
                        "note": "ساخت مخزن GitHub ناموفق: " + git_sync._san(p.stderr, 220),
                        "steps": steps}
            steps.append({"step": "create-repo", "ok": True, "detail": full})
        else:
            steps.append({"step": "create-repo", "ok": True,
                          "detail": "مخزن موجود است — ایجاد مجدد نشد: " + full})
    else:
        view = github_repo_view(full)
        if not view.get("exists"):
            return {"status": FAIL, "created": False,
                    "note": "مخزن %s وجود ندارد — اتصال ممکن نیست" % full}
    url = "https://github.com/" + full + ".git"
    _, cur, _ = _git(d, "remote", "get-url", "origin")
    if cur.strip() and cur.strip() != url:
        # never delete/overwrite an existing remote silently
        return {"status": FAIL, "created": False,
                "note": "Remote متفاوتی از قبل موجود است — جایگزینی بدون تأیید صریح ممنوع است"}
    if not cur.strip():
        _git(d, "remote", "add", "origin", url)
    _git(d, "config", "credential.helper", "!gh auth git-credential")
    steps.append({"step": "remote", "ok": True, "detail": "origin → " + url})
    code, branch, _ = _git(d, "rev-parse", "--abbrev-ref", "HEAD")
    branch = branch.strip() if code == 0 else "main"
    pushed = False
    code, _, err = _git(d, "push", "-u", "origin", branch, timeout=90)
    if code == 0:
        pushed = True
        steps.append({"step": "push", "ok": True, "detail": "git push -u origin " + branch})
    else:
        steps.append({"step": "push", "ok": False,
                      "detail": git_sync._san(err, 200)})
    save_settings(project, {
        "project": project, "repo_name": full, "remote_url": url,
        "visibility": "private" if private else "public",
        "branch": branch, "created_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
    })
    return {"status": OK if pushed else FAIL, "created": create, "pushed": pushed,
            "repo": full, "url": "https://github.com/" + full,
            "visibility": "private" if private else "public", "steps": steps,
            "note": "" if pushed else "اتصال انجام شد ولیpush اولیه ناموفق بود"}


def proposal(project: str, session_id: str = "") -> dict:
    """A ready-to-show Persian proposal. Performs NO write and NO network mutation."""
    st = repo_state(project)
    login = st["github_login"]
    name = suggest_name(project)
    existing = github_repo_view(name) if login else {}
    private = True
    if existing.get("exists") and existing.get("visibility") == "PUBLIC":
        private = False
    if not st["own_repo"]:
        question = ("برای پروژه «%s» مخزن Git اختصاصی وجود ندارد. میخواهی مخزن خصوصی "
                    "با نام پیشنهادی «%s» در حساب %s بسازم و پروژه را به آن متصل کنم؟"
                    % (project, name, login or "GitHub (پس از ورود)"))
    elif not st["connected"]:
        question = ("برای پروژه «%s» مخزن محلی هست ولی به GitHub متصل نیست. میخواهی مخزن "
                    "خصوصی «%s» بسازی و آن را متصل کنی؟" % (project, name))
    else:
        question = ("مخزن پروژه «%s» به «%s» متصل است؛ ادامهٔ عملیات نیازمند تأیید "
                    "یکبارهای است." % (project, st["remote_info"].get("repo") or name))
    return {
        "status": NEEDS_CONFIRM, "project": project,
        "proposed_name": name, "private_default": private,
        "github_login": login,
        "existing_repo": existing,
        "question_fa": question,
        "state": {"own_repo": st["own_repo"], "connected": st["connected"],
                  "branch": st["branch"], "commits": st["commits"],
                  "changed_count": st["changed_count"]},
        "safe_actions": ["بررسی وضعیت", "ساخت APK", "اجرای تست", "مشاهدهٔ تغییرات"],
    }


def ensure_ready(project: str, decision: dict | None = None,
                 decline: bool = False, session_id: str = "") -> dict:
    """The stage that runs BEFORE build/deliver/git-sync in Smart Release.

    decision = the consumed confirmation payload (name/private/create_repo).
    """
    st = repo_state(project)
    if st["conflicts"]:
        return {"status": FAIL, "note": "تعارض در ایندکس git — حل دستی لازم است",
                "state": st}
    if st["connected"]:
        return {"status": OK, "created": False, "connected": True,
                "note": "مخزن اختصاصی متصل است", "state": st,
                "repo": st["remote_info"].get("repo")}
    if decline:
        return {"status": SKIP, "created": False, "connected": False,
                "note": "کاربر ساخت/اتصال مخزن را تأیید نکرد — ارسالی انجام نشد",
                "state": st}
    if not decision:
        p = proposal(project, session_id)
        return {"status": NEEDS_CONFIRM, "created": False, "connected": False,
                "proposal": p, "question_fa": p["question_fa"], "state": st}
    if decision.get("project") and decision["project"] != project:
        return {"status": FAIL, "note": "تأیید به پروژهٔ دیگری تعلق دارد", "state": st}
    name = str(decision.get("name") or suggest_name(project))
    private = bool(decision.get("private", True))
    create = bool(decision.get("create_repo", True))
    if not re.match(r"^[A-Za-z0-9._\-/]{1,100}$", name):
        return {"status": FAIL, "note": "نام مخزن نامعتبر است", "state": st}
    if not st["own_repo"]:
        loc = init_local_repo(project)
        if loc["status"] != OK:
            return dict(loc, state=st)
    if not create:
        return {"status": OK, "created": not st["own_repo"], "connected": False,
                "note": "مخزن محلی آماده است؛ اتصال GitHub طبق تأیید کاربر انجام نشد",
                "state": repo_state(project)}
    link = connect_remote(project, name, create=create, private=private)
    return dict(link, state=repo_state(project))
